/**
 * 右下角让位 —— 悬浮按钮该往左挪多少，**当场量**，不写死。
 *
 * ## 为什么不是"每个页面配一个偏移量"
 *
 * 墩儿的按钮钉在右下角，而这个矿的大屏**右下角几乎每页都压着东西**。
 * 实测（1920×1080，按钮按 66×56 落在右下角）：
 *
 * | 页面 | 右下角（按钮 66×56 那条横带上）是什么 |
 * |---|---|
 * | 安全管理 | 480px 的 `aside.safety__side` |
 * | 智能监控 | 400px 的 `div.monitor__side` |
 * | 设备管理 | 460px 的右栏面板 |
 * | 应急救援 | 380px 的 `aside.emergency__side` |
 * | 数字孪生 | 400px 的 `nav.twin__tabs`（**页签，可点控件**） |
 * | 数据管理 | 1888px 表格面板的右下角 |
 * | 首页 / 统计报表 / 决策指挥 / 成本管理 | 只有底图，干净 |
 *
 * 这正是 `check-panel-overflow.mjs` 立规矩时要抓的那类缺陷：
 * 「浮层盖住面板内容 —— DOM 里那块面板和它的 canvas 都在，计数完全正常，
 * 只有量矩形（或者肉眼看截图）才发现得了」。墩儿自己的按钮不该是新的那一例。
 *
 * 写死的话只有两条路，都不行：
 * - **按页面配一张偏移表**：等于把九个页面的布局复制进墩儿里，页面一改布局，
 *   这张表**不会报错**，只会把按钮重新压回某个页面上（与 `vocab.mjs`
 *   「坐标不进后端」是同一个理由：副本会漂移，且漂移了没人发现）；
 * - **统一加一个很大的 bottom**：按钮会浮到屏幕半腰，反而不像"右下角"。
 *
 * 所以量：**从右下角起，谁在按钮这条横带上，就往左让过谁，一直让到没人**；
 * 没撞上任何东西就按默认的 16px（与页面自己的 16px 边距对齐）。
 *
 * ## "让到没人"要迭代，也不能让出画面
 *
 * 第一版只让一次（躲过最右边那一栏就收工），实测**三页漏网**：
 * 安全/设备/应急的底部是**两块并排**的面板（右栏 400~480 一块，紧挨着左边
 * 还有一块 360~460 的），只让一次正好落在第二块的右端上 —— 看上去躲开了，
 * 压住的其实是隔壁那块。所以这里是个迭代（上限 8 次，实测最多用到 4 次，
 * 在应急救援页）。
 *
 * 迭代还必须有条护栏：**让位不能把按钮让出画面**。设备管理、数据管理两页的
 * 底部整行铺满，一味往左让会一路算到 1916（按钮落到 x=-62，等于消失）。
 * 走到那一步就**停在原地**——原地至少已经躲开了所有窄面板（上面表格里
 * 那三处已知的代价就是从这儿来的）。
 *
 * 让位后的实测落位（1920×1080，2026-09-17 两轮扫描一致；检查脚本里逐页断言）：
 *
 * | 页面 | 按钮距右 | 让过了谁 | 压着谁 |
 * |---|---|---|---|
 * | 首页 / 统计报表 / 决策指挥 / 成本管理 | 16 | 没人挡 | 只有底图 |
 * | 智能监控 | 428 | `div.monitor__side`（400） | 只有底图 |
 * | 数字孪生 | 428 | `nav.twin__tabs`（400，页签） | 只有底图 |
 * | 安全管理 | 804 | 右栏（480）+ 底下并排的 360 面板 | 只有底图 |
 * | 应急救援 | 1137 | 右栏（380）+ 795 起那块 713 的面板（底下并着两块 336 的救援面板） | **同排左边那块 713 面板的右端，压住 62px**（见下） |
 * | 设备管理 | 964 | 右栏（460）+ 并排的 460 面板 | **936px 气泡面板的右下角，压住 62px**（见下） |
 * | 数据管理 | 16 | 没人挡 | **1888px 表格面板的一角**（见下） |
 *
 * 「压着谁」那一列是被断言过的：**十页里没有任何一页压住宽度 < 1/3 画布的
 * 元素**（也就是所有窄面板、列表、页签这些真正会被点/会看的东西），
 * 但有三页压住了宽面板的一角，原因是那三页的底部**整行都被铺满**，
 * 没有第三个位置可选：
 *
 * - **设备管理**：底部一行是 936 的气泡面板 + 两块 460 的面板，首尾相接占满
 *   1888px。让到 964 已经是"最靠右那个不压窄面板"的位置，再让一步就是 1916
 *   —— 按钮会跑出画面左边（66 的按钮让到 1916 意味着它落在 x=-62）。
 *   压住的是那块 936 面板最右下角 62×56，占它的 1%；
 * - **应急救援**：同一条算式 —— 底部那行是 66..779 与 795..1508 两块 713 的面板、
 *   右边再顶着一块 380 的右栏，**中间只剩 779..795 这 16px 的缝**，装不下 66 的按钮。
 *   让到 1137（右边那块面板左沿再留 12px 空隙）时，按钮左沿 717 就搭在左边那块
 *   的右端上。2026-09-17 量的现场：按钮 x 717..783、那块面板 x 66..779
 *   （⚠️ 这一行原来写着"只有底图"—— 是**实测推翻的**：判据报了它压住 713 的面板，
 *   量了一遍确认判据对、注释错，改的是注释）；
 * - **数据管理**：整页就是一块 1888×914 的面板（见 PAGE_WIDE_RATIO），
 *   "旁边"不存在，压的是表格最右下角那一格。
 *
 * 这三处是**明知而接受的**，写在 README §13 的实测表里；`check-duner.mjs`
 * 的逐页扫描断言的是"不压窄元素"这条（它见过红：自证 T7 把 `--duner-right`
 * 手动扳回 16px，在数字孪生页当场压住那个页签）。
 * 它另有一处**盲区**（如实记在 README 第 35 条）：比 2/3 画布还宽的铺底元素
 * 两边都不算 —— 数据管理那块 1888 的表格就是这么被放过去的。
 */

/** 按钮尺寸与默认落位（设计像素，1920×1080 坐标系） */
export const FAB_W = 66
export const FAB_H = 56
/** 按钮下沿距画布底边的距离。与页面自己的 16px 边距一致 */
export const FAB_BOTTOM = 16
/** 不撞任何东西时的右偏移 */
export const FAB_RIGHT = 16
/** 让位后与那一栏之间的空隙 */
const DODGE_GAP = 12
/**
 * "它是可以躲开的一块面板、不是页面的底"的判定：宽度不超过画布宽度的 2/3
 * （1920 下 = 1280px）。
 *
 * 这条线只用来滤掉**铺底的东西**（页面根元素、三维地图容器、整行的包裹层），
 * 不是用来"放过宽面板"。实测的宽度谱系：
 * - 页面的底：地图容器 1920、设备管理 `equipment__row` 1888、
 *   安全管理 `safety__map` 1440、应急救援 `emergency__bottom` 1442
 *   —— 都在 2/3 以上，滤掉；
 * - 真正的内容面板：设备管理那块 936 的、应急救援那块 713 的、
 *   安全/监控/孪生/报表/成本/决策的 400~504 的 —— 全在 2/3 以下，都算"要躲的一栏"。
 *
 * ⚠️ 这条线**不是"躲不躲得开"的判断**（那由下面的"让位不能让出画面"管），
 * 定得太宽会出真事：第一版写成 9/10，安全管理页 1440 宽的地图容器就被当成了
 * 候选，迭代算出来的落点在画面外、被上限截住，按钮于是停在 492 —— **正好压在
 * 那块 360 宽的隐患面板上**。宽面板该不该躲，量的是宽度，不是"躲不躲得开"。
 */
const PAGE_WIDE_RATIO = 2 / 3
/** 太小的装饰不算数（图标点、分隔线、角标） */
const MIN_W = 40
const MIN_H = 20

export interface CornerPlacement {
  /** 按钮右边缘距画布右边框的距离（设计像素）—— 直接写进 CSS 的 `right` */
  right: number
  /** 最后逼着它让位的是谁（`tag.class`）。没让位时为 null —— 排查与检查脚本用 */
  blockedBy: string | null
}

const 描述 = (el: Element): string => {
  const cls = typeof el.className === 'string' ? el.className.trim().split(/\s+/)[0] : ''
  return `${el.tagName.toLowerCase()}${cls ? `.${cls}` : ''}`
}

/**
 * 量出按钮该落在哪。`root` 是墩儿的根元素（它必须在缩放容器里）。
 *
 * 全程用**设备像素**比较、最后再除回设计像素：页面挂在 `ScaleScreen` 的
 * `transform: scale()` 里，`getBoundingClientRect()` 拿到的是缩放后的值，
 * 而 CSS 的 `right` 是缩放前的 —— 两者混用会在 1440×900 上偏出 25%。
 */
export function measureCorner(root: HTMLElement): CornerPlacement {
  const 默认: CornerPlacement = { right: FAB_RIGHT, blockedBy: null }
  const canvas = root.closest('.scale-screen__canvas') as HTMLElement | null
  if (!canvas) return 默认

  const c = canvas.getBoundingClientRect()
  if (!c.width || !c.height) return 默认
  // 设计像素 → 设备像素的比例（1440×900 下是 0.75）
  const scale = c.width / (canvas.offsetWidth || c.width)
  const 小于 = (px: number) => px * scale

  // 按钮自己占的那条横带（设备像素）
  const 带顶 = c.bottom - 小于(FAB_BOTTOM + FAB_H)
  const 带底 = c.bottom - 小于(FAB_BOTTOM)

  // 先把"这条横带上的真内容"挑出来，坐标一次算完（后面要反复用）
  const 候选: { el: Element; left: number; right: number }[] = []
  for (const el of canvas.querySelectorAll('*')) {
    // 自己人（按钮/对话框）不进候选 —— 否则量到自己，按钮会追着自己跑
    if (el.closest('[data-duner-dock]')) continue
    // 三维地图：满屏底图，按钮浮在上面是设计如此（九页里有七页是它）
    if (el.closest('.map-scene')) continue
    if (el.tagName === 'CANVAS' || el.tagName === 'VIDEO' || el.tagName === 'SVG') continue

    const r = el.getBoundingClientRect()
    if (r.width < 小于(MIN_W) || r.height < 小于(MIN_H)) continue
    // 得是"一块面板"而不是"整页的底"（见 PAGE_WIDE_RATIO）
    if (r.width > c.width * PAGE_WIDE_RATIO) continue
    // 与按钮同高才叫撞上：比按钮高的东西（右栏上方的面板）不逼它让位
    if (r.bottom <= 带顶 || r.top >= 带底) continue

    候选.push({ el, left: r.left, right: r.right })
  }

  // ---- 迭代让位：躲过一个，左边往往还并排着下一个 ------------------------
  //
  // 这是**实测**改出来的（第一版只躲一次）：安全/设备/应急三页的底部是
  // **两块并排**的面板（右栏 400~480 一块，紧挨着左边又一块 360~460 的），
  // 只躲一次会正好落在第二块的右端上 —— 看起来"躲开了"，其实压住的是隔壁那块。
  // 所以一直躲到这条横带上没有东西为止（上限 8 次，正常最多两三回）。
  let right = FAB_RIGHT
  let blockedBy: string | null = null
  // 按钮左边缘最多让到这儿（再往左就顶出页面的 16px 边距了）
  const RIGHT_MAX = c.width / scale - FAB_RIGHT - FAB_W
  for (let i = 0; i < 8; i++) {
    const 盒左 = c.right - 小于(right + FAB_W)
    const 盒右 = c.right - 小于(right)
    const 撞上 = 候选.filter((x) => x.right > 盒左 && x.left < 盒右)
    if (!撞上.length) break
    const 最左 = Math.min(...撞上.map((x) => x.left))
    const 下一个 = Math.round((c.right - 最左) / scale + DODGE_GAP)
    // 让位不能让出画面。这一步**必须有**：设备管理/数据管理两页底部整行铺满，
    // 一味往左让会一路让到画面外，按钮就从"右下角"变成"看不见"。
    // 停在当前位置 —— 它至少已经躲开了所有窄面板（就是上面那些候选）。
    if (下一个 > RIGHT_MAX) break
    right = 下一个
    blockedBy = 描述(撞上.find((x) => x.left === 最左)?.el ?? 撞上[0].el)
  }
  return blockedBy === null ? { right: FAB_RIGHT, blockedBy: null } : { right, blockedBy }
}
