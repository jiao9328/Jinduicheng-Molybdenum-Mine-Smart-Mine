/**
 * 待接续的反问 —— 让多轮对话能接上。
 *
 * ## 为什么需要它
 *
 * 用户说「生成处置工单，对象北帮3号台阶，事由裂缝」，墩儿反问「责任人是谁」，
 * 用户点「王建国」。**这句话会被当成一条全新的指令重新识别**，
 * 而「王建国」三个字单独出现不属于任何意图 —— 于是又反问一遍同一句。
 * 用户点了自己的选项，却回到原点。
 *
 * 前面那句里的「北帮3号台阶」「裂缝」只存在于上一次调用的局部变量里，
 * 这条链路一返回就没了。所以代价最小的做法是：把**这次问的是哪个参数、
 * 已经有哪些参数**记一小会儿，用户的下一句话若能填上，就接着跑同一个工具。
 *
 * ## 为什么放内存，而 `pending_confirm` 非落库不可
 *
 * 这两者看着都是"记住一下"，但**要保的性质完全不同**：
 *
 * - `pending_confirm` 是"已获用户授权"的凭据。它必须扛住并发（两个同 token
 *   的确认请求只能成功一个）、必须能在进程重启后依然一次性 —— 所以落库，
 *   靠 `UPDATE ... WHERE redeemed = 0` 单条 SQL 做闸门。**可猜的令牌
 *   等于任何人都能替别人确认一次写操作。**
 * - 这里记的是"我上一句问了他什么"。丢了会怎样？用户重说一遍而已。
 *   它**不构成任何授权** —— 接续之后照样要过 `policy.authorize`，
 *   写操作照样要发确认卡、照样要用户点确认。猜中它也写不进任何东西。
 *
 * 为一个"丢了就重说一遍"的东西付落库的代价（表、迁移、清理任务）不划算，
 * 所以这里用进程内的 Map，并且**明确地**接受"重启即丢"。
 *
 * ## key 是用户 id，不是会话
 *
 * 同一句反问只对**发问的那个人**有意义。用全局的单个槽位会让 A 的反问
 * 被 B 的下一句话接走 —— 而 B 根本没看到那个问题，他填的"王建国"
 * 会被拿去建 A 的工单。这也是为什么过期时间取得很短。
 */

/** 反问的接续有效期。比确认令牌（60s）长 —— 人要想一下才回话 */
const TTL_MS = 5 * 60_000

/** userId → { intent, tool, slots, slot, at } */
const waiting = new Map()

/** 记下"我在等他回答哪个参数"。同一用户只保留最新一条反问 */
export function remember(userId, rec) {
  if (!userId) return
  waiting.set(userId, { ...rec, at: Date.now() })
}

/**
 * 取出并**清掉**待接续的反问。
 *
 * 取出即清是刻意的：一句反问只该被回答一次。留着它的话，
 * 用户接下来随便说句什么都会被塞进那个参数里 ——
 * 他问「今天产量怎么样」，得到的是拿"今天产量怎么样"当责任人的一张工单。
 */
export function take(userId) {
  const rec = waiting.get(userId)
  if (!rec) return null
  waiting.delete(userId)
  if (Date.now() - rec.at > TTL_MS) return null
  return rec
}

/** 主动丢弃（用户说了别的话、或那条路走不通了） */
export function forget(userId) {
  waiting.delete(userId)
}

/** 只读地看一眼，不消费。自检脚本与排障用 */
export function peek(userId) {
  return waiting.get(userId) ?? null
}
